/**
 * RFC 3834-based automated / bulk / list mail classifier.
 *
 * Pure function — no I/O, no persistence, no record coupling.
 * Wiring to the sync pipeline is handled separately (ADR 0002 / ADR 0009 Topic 3).
 */

export type AutomatedKind = "auto-replied" | "auto-generated" | "list" | "bulk";

export interface AutomatedClassification {
  automated: boolean;
  kind: AutomatedKind | null;
  signals: string[];
}

/**
 * Resolves a single header value from a case-insensitive header map.
 * Returns undefined when the header is absent.
 * When the header is an array, returns the first element.
 */
function getHeader(
  headers: Record<string, string | string[] | undefined>,
  name: string,
): string | undefined {
  const lower = name.toLowerCase();
  for (const key of Object.keys(headers)) {
    if (key.toLowerCase() === lower) {
      const val = headers[key];
      if (val === undefined) return undefined;
      return Array.isArray(val) ? val[0] : val;
    }
  }
  return undefined;
}

/**
 * Returns true when the header is present (and non-undefined) for any casing.
 */
function hasHeader(headers: Record<string, string | string[] | undefined>, name: string): boolean {
  const lower = name.toLowerCase();
  for (const key of Object.keys(headers)) {
    if (key.toLowerCase() === lower) {
      return headers[key] !== undefined;
    }
  }
  return false;
}

/**
 * Extracts the primary token from a structured header value.
 * `auto-replied; owner-email=noreply@example.com` → `auto-replied`
 */
function primaryToken(value: string): string {
  return value.split(";")[0]?.trim().toLowerCase() ?? "";
}

/**
 * Classifies an inbound mail message as automated, bulk, list, or human based
 * on its headers, following RFC 3834 §5 and common mail system conventions.
 *
 * Priority when multiple signals fire: auto-replied > auto-generated > list > bulk.
 *
 * Header names are matched case-insensitively. Array header values are treated
 * as if each element were a separate header line (first element wins for
 * single-value headers).
 *
 * @param headers - Raw message headers. Values may be a string, an array of
 *   strings (multi-value header), or undefined.
 * @returns Classification result with `automated`, `kind`, and all matched `signals`.
 */
export function classifyAutomated(
  headers: Record<string, string | string[] | undefined>,
): AutomatedClassification {
  const signals: string[] = [];

  // --- Auto-Submitted (RFC 3834 §5) ---
  const autoSubmitted = getHeader(headers, "Auto-Submitted");
  if (autoSubmitted !== undefined) {
    const token = primaryToken(autoSubmitted);
    if (token !== "no") {
      // Treat as auto-replied or auto-generated; unknown values → auto-generated.
      if (token === "auto-replied") {
        signals.push("Auto-Submitted:auto-replied");
      } else {
        // auto-generated and any unrecognised value
        signals.push("Auto-Submitted:auto-generated");
      }
    }
  }

  // --- X-Autoreply ---
  if (hasHeader(headers, "X-Autoreply")) {
    signals.push("X-Autoreply");
  }

  // --- X-Autorespond ---
  if (hasHeader(headers, "X-Autorespond")) {
    signals.push("X-Autorespond");
  }

  // --- X-Auto-Response-Suppress (All | OOF | AutoReply) ---
  const autoResponseSuppress = getHeader(headers, "X-Auto-Response-Suppress");
  if (autoResponseSuppress !== undefined) {
    const upper = autoResponseSuppress.toUpperCase();
    if (upper.includes("ALL") || upper.includes("OOF") || upper.includes("AUTOREPLY")) {
      signals.push("X-Auto-Response-Suppress");
    }
  }

  // --- Precedence ---
  const precedence = getHeader(headers, "Precedence");
  if (precedence !== undefined) {
    const token = primaryToken(precedence);
    if (token === "bulk" || token === "junk") {
      signals.push("Precedence:bulk");
    } else if (token === "list") {
      signals.push("Precedence:list");
    }
  }

  // --- List-Id ---
  if (hasHeader(headers, "List-Id")) {
    signals.push("List-Id");
  }

  // --- List-Unsubscribe ---
  if (hasHeader(headers, "List-Unsubscribe")) {
    signals.push("List-Unsubscribe");
  }

  if (signals.length === 0) {
    return { automated: false, kind: null, signals: [] };
  }

  // Determine winning kind by priority: auto-replied > auto-generated > list > bulk
  let kind: AutomatedKind;

  const hasAutoReplied =
    signals.includes("Auto-Submitted:auto-replied") ||
    signals.includes("X-Autoreply") ||
    signals.includes("X-Autorespond") ||
    signals.includes("X-Auto-Response-Suppress");

  const hasAutoGenerated = signals.includes("Auto-Submitted:auto-generated");

  const hasList =
    signals.includes("Precedence:list") ||
    signals.includes("List-Id") ||
    signals.includes("List-Unsubscribe");

  if (hasAutoReplied) {
    kind = "auto-replied";
  } else if (hasAutoGenerated) {
    kind = "auto-generated";
  } else if (hasList) {
    kind = "list";
  } else {
    // hasBulk is the only remaining case (Precedence:bulk / Precedence:junk)
    kind = "bulk";
  }

  return { automated: true, kind, signals };
}
