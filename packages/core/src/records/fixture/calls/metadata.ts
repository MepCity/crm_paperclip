/** Temporary routing decision, identical to Tasks; form research will confirm Who_Id. */
export const callsWhoTargets = ["Contacts", "Leads"] as const;
export const callsWhatTargets = relatedTargets
  .filter((row) => row.module === "Calls" && row.href === `${row.sourceModule}/{ENTITYID}/Calls`)
  .map((row) => row.sourceModule)
  .filter((module) => !callsWhoTargets.some((target) => target === module));
export const callsMetadata: ModuleMetadata = {
  ...callsMetadataSource,
  fields: callsMetadataSource.fields.map((field) => ({
    ...field,
    ...(field.dataType === "picklist" ? { picklist: callsPicklists[field.apiName] } : {}),
    ...(field.apiName === "Who_Id"
      ? { lookup: { module: "Contacts", modules: callsWhoTargets } }
      : {}),
    ...(field.apiName === "What_Id"
      ? { lookup: { module: "Accounts", modules: callsWhatTargets } }
      : {}),
  })),
};
