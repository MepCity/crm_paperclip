export const eventsWhoTargets = ["Contacts", "Leads"] as const;
export const eventsWhatTargets = relatedTargets
  .filter((row) => row.module === "Events" && row.href === `${row.sourceModule}/{ENTITYID}/Events`)
  .map((row) => row.sourceModule)
  .filter((module) => !eventsWhoTargets.some((target) => target === module));
export const eventsMetadata: ModuleMetadata = {
  ...eventsMetadataSource,
  fields: eventsMetadataSource.fields.map((field) => ({
    ...field,
    ...(field.dataType === "picklist" ? { picklist: eventsPicklists[field.apiName] } : {}),
    ...(field.apiName === "Who_Id"
      ? { lookup: { module: "Contacts", modules: eventsWhoTargets } }
      : {}),
    ...(field.apiName === "What_Id"
      ? { lookup: { module: "Accounts", modules: eventsWhatTargets } }
      : {}),
  })),
};
